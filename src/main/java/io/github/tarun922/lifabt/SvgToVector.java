package io.github.tarun922.lifabt;

import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.xml.sax.InputSource;

import javax.xml.parsers.DocumentBuilderFactory;
import java.io.StringReader;
import java.util.Locale;

/**
 * Converts a Lucide SVG (stroke based, 24x24) into an Android VectorDrawable.
 * Supports path, line, polyline, polygon, circle, ellipse, rect and nested g.
 * Transforms are not supported (Lucide icons don't use them).
 */
final class SvgToVector {

    private SvgToVector() {}

    static String convert(String svgText) throws Exception {
        DocumentBuilderFactory f = DocumentBuilderFactory.newInstance();
        // Downloaded content is untrusted: no DTDs, no external entities.
        f.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
        f.setXIncludeAware(false);
        f.setExpandEntityReferences(false);
        Document doc = f.newDocumentBuilder().parse(new InputSource(new StringReader(svgText)));
        Element svg = doc.getDocumentElement();
        if (!"svg".equals(svg.getTagName())) {
            throw new IllegalArgumentException("Not an SVG document");
        }

        String[] vb = attr(svg, "viewBox", "0 0 24 24").trim().split("[\\s,]+");
        if (vb.length != 4) throw new IllegalArgumentException("Bad viewBox");
        double vw = Double.parseDouble(vb[2]);
        double vh = Double.parseDouble(vb[3]);
        String sw = attr(svg, "stroke-width", "2");
        String cap = attr(svg, "stroke-linecap", "round");
        String join = attr(svg, "stroke-linejoin", "round");

        StringBuilder out = new StringBuilder();
        out.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
        out.append("<!-- Generated by io.github.tarun922.lifabt. Do not edit. -->\n");
        out.append("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n");
        out.append("    android:width=\"24dp\"\n    android:height=\"24dp\"\n");
        out.append("    android:viewportWidth=\"").append(fmt(vw)).append("\"\n");
        out.append("    android:viewportHeight=\"").append(fmt(vh)).append("\">\n");
        walk(svg, out, sw, cap, join);
        out.append("</vector>\n");
        return out.toString();
    }

    private static void walk(Element parent, StringBuilder out, String sw, String cap, String join) {
        for (Node n = parent.getFirstChild(); n != null; n = n.getNextSibling()) {
            if (!(n instanceof Element)) continue;
            Element e = (Element) n;
            String d;
            switch (e.getTagName()) {
                case "g":
                    walk(e, out, sw, cap, join);
                    continue;
                case "path":
                    d = attr(e, "d", "").trim().replaceAll("\\s+", " ");
                    break;
                case "line":
                    d = "M" + num(e, "x1") + "," + num(e, "y1") + " L" + num(e, "x2") + "," + num(e, "y2");
                    break;
                case "polyline":
                    d = points(attr(e, "points", ""), false);
                    break;
                case "polygon":
                    d = points(attr(e, "points", ""), true);
                    break;
                case "circle": {
                    double r = Double.parseDouble(num(e, "r"));
                    d = ellipse(Double.parseDouble(num(e, "cx")), Double.parseDouble(num(e, "cy")), r, r);
                    break;
                }
                case "ellipse":
                    d = ellipse(Double.parseDouble(num(e, "cx")), Double.parseDouble(num(e, "cy")),
                            Double.parseDouble(num(e, "rx")), Double.parseDouble(num(e, "ry")));
                    break;
                case "rect":
                    d = rect(e);
                    break;
                default:
                    continue; // title, desc, defs, etc.
            }
            if (d.isEmpty()) continue;

            String fill = attr(e, "fill", "none");
            out.append("    <path\n");
            out.append("        android:pathData=\"").append(d).append("\"\n");
            if (!"none".equals(fill)) {
                out.append("        android:fillColor=\"#FF000000\"\n");
            }
            out.append("        android:strokeColor=\"#FF000000\"\n");
            out.append("        android:strokeWidth=\"").append(attr(e, "stroke-width", sw)).append("\"\n");
            out.append("        android:strokeLineCap=\"").append(attr(e, "stroke-linecap", cap)).append("\"\n");
            out.append("        android:strokeLineJoin=\"").append(attr(e, "stroke-linejoin", join)).append("\"/>\n");
        }
    }

    private static String points(String pts, boolean close) {
        String[] v = pts.trim().split("[\\s,]+");
        if (v.length < 4) return "";
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i + 1 < v.length; i += 2) {
            sb.append(i == 0 ? "M" : " L").append(v[i]).append(",").append(v[i + 1]);
        }
        if (close) sb.append(" Z");
        return sb.toString();
    }

    private static String ellipse(double cx, double cy, double rx, double ry) {
        return "M" + fmt(cx - rx) + "," + fmt(cy)
                + " a" + fmt(rx) + "," + fmt(ry) + " 0 1,0 " + fmt(2 * rx) + ",0"
                + " a" + fmt(rx) + "," + fmt(ry) + " 0 1,0 " + fmt(-2 * rx) + ",0 Z";
    }

    private static String rect(Element e) {
        double x = Double.parseDouble(attr(e, "x", "0"));
        double y = Double.parseDouble(attr(e, "y", "0"));
        double w = Double.parseDouble(num(e, "width"));
        double h = Double.parseDouble(num(e, "height"));
        String rxs = attr(e, "rx", null);
        String rys = attr(e, "ry", null);
        double rx = rxs != null ? Double.parseDouble(rxs) : (rys != null ? Double.parseDouble(rys) : 0);
        double ry = rys != null ? Double.parseDouble(rys) : rx;
        rx = Math.min(rx, w / 2);
        ry = Math.min(ry, h / 2);
        if (rx == 0 && ry == 0) {
            return "M" + fmt(x) + "," + fmt(y) + " H" + fmt(x + w) + " V" + fmt(y + h) + " H" + fmt(x) + " Z";
        }
        String arc = "A" + fmt(rx) + "," + fmt(ry) + " 0 0 1 ";
        return "M" + fmt(x + rx) + "," + fmt(y)
                + " H" + fmt(x + w - rx) + " " + arc + fmt(x + w) + "," + fmt(y + ry)
                + " V" + fmt(y + h - ry) + " " + arc + fmt(x + w - rx) + "," + fmt(y + h)
                + " H" + fmt(x + rx) + " " + arc + fmt(x) + "," + fmt(y + h - ry)
                + " V" + fmt(y + ry) + " " + arc + fmt(x + rx) + "," + fmt(y) + " Z";
    }

    private static String num(Element e, String name) {
        String v = e.getAttribute(name);
        if (v.isEmpty()) {
            if (name.equals("cx") || name.equals("cy")) return "0";
            throw new IllegalArgumentException("<" + e.getTagName() + "> missing " + name);
        }
        return v;
    }

    private static String attr(Element e, String name, String def) {
        return e.hasAttribute(name) ? e.getAttribute(name) : def;
    }

    private static String fmt(double v) {
        if (v == Math.rint(v)) return String.valueOf((long) v);
        String s = String.format(Locale.ROOT, "%.4f", v);
        s = s.replaceAll("0+$", "");
        return s.endsWith(".") ? s.substring(0, s.length() - 1) : s;
    }
}
